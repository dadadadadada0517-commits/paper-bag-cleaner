function forPlayer(l) {
  if (G.char !== 'witch') return l;
  const three = l.length === 3, who = three ? l[0] : null, name = three ? l[1] : l[0];
  let text = three ? l[2] : l[1];
  if (text.startsWith('哼哼～這次我也有幫忙')) return ['hero', '小編', '……這次，主任辛苦了。（比讚）']; // 結局：換小編誇她
  if (who === 'hero' || (!three && name === '小編')) return ['witch', '豪鬼主任', WITCH_TEXT[text] || text.replace(/^……/, '')];
  text = text.replace(/小編大哥|小編大叔|小編/g, '主任');
  return three ? [who, name, text] : [name, text];
}
